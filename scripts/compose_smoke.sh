#!/usr/bin/env bash
# Production-image smoke test (CI job `compose-smoke`). Uses docker-compose.yml as shipped, with a generated TEST .env: paper mode,
# no market-data network, no exchange credentials. Nothing is deployed; everything is removed at the end.
# Checks, each one fails the job on its own:
#   1. compose refuses to start without a .env file
#   2. the production image has no test code in it and runs as a non-root user
#   3. the backend becomes healthy (Docker HEALTHCHECK) and answers /health/live and /health
#   4. every database migration is applied at startup
#   5. a restart keeps the database (same baseline records before and after)
#   6. a stop is graceful (exit code 0, within the timeout)
#   7. a missing required setting (production without a PostgreSQL URL) and an invalid setting both refuse to start
# Evidence (logs, image facts, unpinned packages) goes to ci-out/.
set -euo pipefail
cd "$(dirname "$0")/.."
OUT=ci-out
mkdir -p "$OUT"
: > "$OUT/smoke.txt"
P="docker compose -p dewakosmoke"
ok()   { echo "ok    $*" | tee -a "$OUT/smoke.txt"; }
fail() { echo "FAIL  $*" | tee -a "$OUT/smoke.txt"; exit 1; }
cleanup() {
  $P logs --no-color > "$OUT/compose.log" 2>&1 || true
  $P down -v --remove-orphans > /dev/null 2>&1 || true
  rm -f .env
}
trap cleanup EXIT

[ -e .env ] && fail ".env already exists in the checkout (it must never be committed)"

# 1 -------------------------------------------------------------------------------------------------------------------------
# the optional profile services' required variables are supplied here, so the only thing missing is the .env file itself
if POSTGRES_PASSWORD=x REDIS_PASSWORD=x $P config -q > "$OUT/no-env.log" 2>&1; then fail "compose accepted a configuration with no .env file"; fi
grep -qiE "env file .*\.env.*not found|\.env: no such file" "$OUT/no-env.log" \
  || { cat "$OUT/no-env.log"; fail "compose failed without .env, but not because of the missing .env file"; }
ok "compose refuses to start without .env: $(head -c 160 "$OUT/no-env.log")"

cat > .env <<'EOF'
# generated by scripts/compose_smoke.sh for CI only (test values, no credentials)
DEWAKO_ENV=development
DEWAKO_MARKET_DATA=none
DEWAKO_PAPER_TRADING=1
DEWAKO_ALLOW_CODE_PLUGINS=0
# the optional postgres/redis profile services are not started; their required variables get CI test values
POSTGRES_PASSWORD=ci-smoke-FAKE
REDIS_PASSWORD=ci-smoke-FAKE
EOF

# 2 -------------------------------------------------------------------------------------------------------------------------
$P build backend > "$OUT/build.log" 2>&1 || { tail -40 "$OUT/build.log"; fail "production image did not build"; }
IMG=dewakosmoke-backend                        # compose names a built image <project>-<service>
docker image inspect "$IMG" > /dev/null 2>&1 || fail "built image $IMG not found"
docker run --rm --entrypoint sh "$IMG" -c 'test ! -e /app/tests' || fail "the production image contains /app/tests"
uid=$(docker run --rm --entrypoint id "$IMG" -u)
[ "$uid" = "10001" ] || fail "the production image runs as uid $uid, expected the non-root user 10001"
ok "production image: no tests inside, runs as uid 10001"
docker run --rm --entrypoint pip "$IMG" freeze > "$OUT/image-pip-freeze.txt"
python3 - "$OUT/image-pip-freeze.txt" backend/constraints-test.txt > "$OUT/image-unpinned-packages.txt" <<'PY'
import sys, re
norm = lambda n: re.sub(r"[-_.]+", "-", n).lower()
frozen = {norm(l.split("==")[0]): l.strip() for l in open(sys.argv[1]) if "==" in l}
pinned = {norm(l.split("==")[0]) for l in open(sys.argv[2]) if "==" in l and not l.startswith("#")}
extra = sorted(v for k, v in frozen.items() if k not in pinned)
print("installed in the image but not pinned by constraints-test.txt:" if extra else "every installed package is pinned")
print("\n".join(extra))
PY
cat "$OUT/image-unpinned-packages.txt"
docker image inspect python:3.12-slim --format '{{index .RepoDigests 0}}' > "$OUT/base-image-digest.txt" 2>/dev/null || true

# 3 -------------------------------------------------------------------------------------------------------------------------
$P up -d backend > /dev/null
CID=$($P ps -q backend)
wait_healthy() {
  for _ in $(seq 1 60); do
    s=$(docker inspect -f '{{.State.Health.Status}}' "$CID" 2>/dev/null || echo none)
    [ "$s" = "healthy" ] && return 0
    [ "$(docker inspect -f '{{.State.Running}}' "$CID")" = "true" ] || return 1
    sleep 2
  done
  return 1
}
wait_healthy || fail "backend did not become healthy"
live=$(curl -fsS http://127.0.0.1:8000/health/live) || fail "/health/live did not answer"
echo "$live" | grep -q '"alive"' || fail "/health/live answered $live"
code=$(curl -s -o "$OUT/health.json" -w '%{http_code}' http://127.0.0.1:8000/health)
python3 -c "import json,sys; d=json.load(open('$OUT/health.json')); sys.exit(0 if d.get('status') in ('ok','not_ready','degraded') else 1)" \
  || fail "/health returned HTTP $code with an unexpected body: $(cat "$OUT/health.json")"
ok "healthy; /health/live alive; /health HTTP $code $(cat "$OUT/health.json")"

# 4 -------------------------------------------------------------------------------------------------------------------------
probe() {
  $P exec -T backend python -c "
import hashlib, sqlite3
from dewako.persistence.migrations import MIGRATIONS
c = sqlite3.connect('file:/state/dewako_trading.db?mode=ro', uri=True)
ver = c.execute('SELECT MAX(version) FROM schema_version').fetchone()[0]
base = c.execute('SELECT COUNT(*) FROM safety_state').fetchone()[0]
first = c.execute('SELECT id, created_at, row_hash FROM audit_log ORDER BY id LIMIT 1').fetchone()
n_audit = c.execute('SELECT COUNT(*) FROM audit_log').fetchone()[0]
print(ver, max(v for v, _, _ in MIGRATIONS), base, hashlib.sha256(repr(first).encode()).hexdigest()[:16], n_audit)"
}
read -r ver want nbase h1 na1 <<< "$(probe)"
[ "$ver" = "$want" ] || fail "schema version $ver after startup, expected $want"
[ "$nbase" -gt 0 ] || fail "no baseline safety records after startup"
ok "migrations applied at startup (schema version $ver of $want; $nbase baseline safety records)"

# 5 -------------------------------------------------------------------------------------------------------------------------
$P restart backend > /dev/null
wait_healthy || fail "backend did not become healthy after a restart"
read -r ver2 _ nbase2 h2 na2 <<< "$(probe)"
# the same database file must still be there: same schema, same baseline records, the same first audit record, and the audit log
# only grows (a restart appends startup events; a recreated database would start a new chain)
[ "$ver2" = "$ver" ] && [ "$nbase2" = "$nbase" ] && [ "$h2" = "$h1" ] && [ "$na2" -ge "$na1" ] \
  || fail "database changed across a restart (schema $ver->$ver2, safety rows $nbase->$nbase2, first audit $h1->$h2, audit rows $na1->$na2)"
ok "restart keeps the database (schema $ver2, $nbase2 safety records, same first audit record, audit rows $na1 -> $na2)"

# 6 -------------------------------------------------------------------------------------------------------------------------
t0=$(date +%s)
$P stop -t 30 backend > /dev/null
dt=$(( $(date +%s) - t0 ))
rc=$(docker inspect -f '{{.State.ExitCode}}' "$CID")
[ "$rc" = "0" ] || fail "stop exited with code $rc (expected a graceful 0)"
[ "$dt" -lt 30 ] || fail "stop took ${dt}s (timeout 30s)"
ok "graceful stop: exit code 0 in ${dt}s"

# 7 -------------------------------------------------------------------------------------------------------------------------
refuses() {   # $1 = description, rest = extra -e settings
  local what=$1; shift
  set +e
  timeout 90 $P run --rm --no-deps "$@" backend > "$OUT/refuse.log" 2>&1
  local r=$?
  set -e
  [ "$r" -ne 0 ] && [ "$r" -ne 124 ] || { tail -20 "$OUT/refuse.log"; fail "$what: the backend did not refuse to start (exit $r)"; }
  ok "$what: refused to start (exit $r): $(grep -m1 -oE '(ConfigError|ValueError).*' "$OUT/refuse.log" | head -c 160)"
}
refuses "production without DEWAKO_DATABASE_URL" -e DEWAKO_ENV=production -e DEWAKO_DATABASE_URL=
refuses "invalid DEWAKO_STOP_SUSPECT_SPREAD_PCT" -e DEWAKO_STOP_SUSPECT_SPREAD_PCT=not-a-number
echo "compose smoke: all checks passed" | tee -a "$OUT/smoke.txt"
